package lesson.test;

public class Test {
    static void main(String[] args) {
        System.out.println(10 / 4); // 2
        System.out.println((int) 7.8); // 7
        System.out.println(17 / 5); // 3
        System.out.println(17 % 5); // 2
        System.out.println(17.0 / 5); // 3.4
        System.out.println((double) 17 / 5);  // 3.4
        System.out.println((double) (17 / 5)); // 3.00
        System.out.println((int) 3.99); // 3
        System.out.println("3" + 4 + 5); // "345"
        System.out.println(3 + 4 + "5"); // "75"
    }
}